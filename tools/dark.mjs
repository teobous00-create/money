import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, colorScheme: 'dark' });
const p = await ctx.newPage();
await p.goto(process.env.URL); await p.waitForTimeout(600);
await p.click('[aria-label=Settings]'); await p.waitForTimeout(400);
await p.getByText('Import from 1Money').click(); await p.waitForTimeout(400);
await p.setInputFiles('input[type=file]', process.env.CSV); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Import', exact: true }).click(); await p.waitForTimeout(300);
await p.getByText('Go to accounts').click(); await p.waitForTimeout(1200);
await p.screenshot({ path: process.env.OUT + '/d1.png' });
await p.click('.nav-item:nth-child(4)'); await p.waitForTimeout(1200);
await p.screenshot({ path: process.env.OUT + '/d2.png' });
await p.click('.nav-item:nth-child(2)'); await p.waitForTimeout(500);
await p.locator('.cat-tile').filter({ hasText: 'Σπίτι' }).first().dispatchEvent('pointerdown');
await p.waitForTimeout(700);
await p.locator('.cat-tile').filter({ hasText: 'Σπίτι' }).first().dispatchEvent('pointerup');
await p.waitForTimeout(1200);
await p.screenshot({ path: process.env.OUT + '/d3.png' });
await b.close();
