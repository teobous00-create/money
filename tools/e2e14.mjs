import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const errors = []; p.on('pageerror', e => errors.push(e.message));
const ok = (c, m) => console.log((c ? 'ok  ' : 'FAIL') + ' ' + m);
const OUT = process.env.OUT;
const top = () => p.locator('.sheet').last();
await p.goto(process.env.URL); await p.waitForTimeout(700);
await p.click('[aria-label=Settings]'); await p.waitForTimeout(400);
await p.getByText('Import from 1Money').click(); await p.waitForTimeout(400);
await p.setInputFiles('input[type=file]', process.env.CSV); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Import', exact: true }).click(); await p.waitForTimeout(400);
await p.getByText('Go to accounts').click(); await p.waitForTimeout(600);
await p.click('.nav-item:nth-child(3)'); await p.waitForTimeout(800);
ok(await p.locator('.favs').count() === 0, 'no favorites bar yet');
await p.click('[aria-label="Add transaction"]'); await p.waitForTimeout(800);
await top().locator('.cat-tile', { hasText: 'Supermarket' }).first().click(); await p.waitForTimeout(700);
await top().locator('.subchip', { hasText: 'Καφές' }).click();
for (const k of ['3', ',', '5']) await top().locator(`.key[aria-label="${k}"]`).click();
await top().locator('[aria-label="Add to favorites"]').click(); await p.waitForTimeout(500);
ok(/Added to favorites/.test(await p.locator('.toast').innerText()), 'starred');
ok(await top().locator('[aria-label="Remove from favorites"]').count() === 1, 'star filled');
await p.screenshot({ path: `${OUT}/f0.png` });
await p.goBack(); await p.waitForTimeout(700);
ok(await p.locator('.fav').count() === 1 && /Καφές\s*3,50€/.test(await p.locator('.fav').innerText()), 'chip on Transactions: ' + await p.locator('.fav').innerText());
await p.screenshot({ path: `${OUT}/f1.png` });
const today = () => p.locator('.screen .day-head').first().innerText();
const count = () => p.evaluate(() => Object.values(window.__money.getState().transactions).filter(t => !t.deleted_at).length);
const n0 = await count();
await p.locator('.fav').click(); await p.waitForTimeout(900);
ok(/✓ Καφές 3,50 €/.test(await p.locator('.toast').innerText()), 'one tap saves: ' + await p.locator('.toast').innerText());
const n1 = await count();
ok(n1 === n0 + 1 && /today/i.test(await today()), `added for today (${n0}→${n1}, ${(await today()).replace(/\n/g, ' ')})`);
await p.locator('.fav').dblclick(); await p.waitForTimeout(1000);
ok(await count() === n0 + 1, 'double tap does not save');
ok(/3,5/.test((await top().locator('.amount').innerText()).replace(/\s/g, '')) && /Supermarket/.test(await top().innerText()), 'double tap opens it filled in');
await top().locator('[aria-label="Remove from favorites"]').click(); await p.waitForTimeout(500);
await p.goBack(); await p.waitForTimeout(800);
ok(await p.locator('.fav').count() === 0, 'removed from favorites');
await p.reload(); await p.waitForTimeout(1000);
console.log('errors:', errors.length ? errors : 'none');
await b.close();
