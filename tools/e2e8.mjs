import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: 'dark' });
const p = await ctx.newPage();
const errors = []; p.on('pageerror', e => errors.push(e.message));
const ok = (c, m) => console.log((c ? 'ok  ' : 'FAIL') + ' ' + m);
const OUT = process.env.OUT;
const top = () => p.locator('.sheet').last();
await p.goto(process.env.URL); await p.waitForTimeout(700);
await p.click('[aria-label=Settings]'); await p.waitForTimeout(400);
await p.getByText('Import from 1Money').click(); await p.waitForTimeout(400);
await p.setInputFiles('input[type=file]', process.env.CSV); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Import', exact: true }).click(); await p.waitForTimeout(400);
await p.getByText('Go to accounts').click(); await p.waitForTimeout(600);
await p.click('.nav-item:nth-child(2)'); await p.waitForTimeout(1000);
const cdp = await ctx.newCDPSession(p);
const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] });
const hold = async (loc) => { const bb = await loc.boundingBox(); await touch('touchStart', bb.x + bb.width / 2, bb.y + bb.height / 2); await p.waitForTimeout(650); await touch('touchEnd', 0, 0); await p.waitForTimeout(900); };
const count = () => p.evaluate(() => [...document.querySelectorAll('.cat-tile')].length);
const before = await count();
await hold(p.locator('.screen .cat-tile').filter({ hasText: 'Διασκέδαση' }).first());
await p.locator('.sheet [aria-label=Edit]').first().click(); await p.waitForTimeout(800);
await top().getByText('Merge into another category').click(); await p.waitForTimeout(500);
await top().locator('.list-row', { hasText: 'Supermarket' }).first().click(); await p.waitForTimeout(300);
const btn = top().getByRole('button', { name: /^Move \d+ entries to Supermarket$/ });
await btn.scrollIntoViewIfNeeded(); await p.screenshot({ path: `${OUT}/m1.png` });
const n = Number((await btn.innerText()).match(/\d+/)[0]);
ok(n > 100, `button says Move ${n} entries`);
await btn.click(); await p.waitForTimeout(1200);
ok(await count() === before - 1, 'Διασκέδαση hidden from the grid');
await hold(p.locator('.screen .cat-tile').filter({ hasText: 'Supermarket' }).first());
await p.locator('.sheet [aria-label=Edit]').first().click(); await p.waitForTimeout(800);
const subs = await top().locator('.sub-row').allInnerTexts();
ok(subs.filter(s => /^Καφές/.test(s.trim())).length === 1, 'Καφές joined (only one): ' + subs.join(' | '));
ok(subs.some(s => /Ποτά/.test(s)) && subs.some(s => /Φαγητό/.test(s)) && subs.some(s => /Δώρο/.test(s)), 'Ποτά, Φαγητό, Δώρο added');
await p.screenshot({ path: `${OUT}/m2.png` });
console.log('errors:', errors.length ? errors : 'none');
await b.close();
