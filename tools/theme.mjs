import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: 'light' });
const p = await ctx.newPage(); const errors=[]; p.on('pageerror', e => errors.push(e.message));
const bg = () => p.evaluate(() => getComputedStyle(document.body).backgroundColor);
const ok = (c, m) => console.log((c ? 'ok  ' : 'FAIL') + ' ' + m);
await p.goto('http://localhost:4173/'); await p.waitForTimeout(800);
const light = await bg();
await p.click('[aria-label=Settings]'); await p.waitForTimeout(500);
await p.locator('.seg button', { hasText: 'Dark' }).click(); await p.waitForTimeout(500);
ok(await bg() !== light, 'dark applied: ' + await bg());
await p.screenshot({ path: process.argv[2] + '/t1.png' });
await p.reload(); await p.waitForTimeout(800);
ok(await bg() === 'rgb(13, 15, 18)', 'kept after reload');
ok(await p.evaluate(() => document.querySelector('meta[name=theme-color]').content) === '#0d0f12', 'status bar dark');
await p.click('[aria-label=Settings]'); await p.waitForTimeout(500);
await p.locator('.seg button', { hasText: 'Phone' }).click(); await p.waitForTimeout(400);
ok(await bg() === light, 'back to phone setting (light)');
console.log('errors', errors);
await b.close();
