import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const errors = []; p.on('pageerror', e => errors.push(e.message));
const ok = (c, m) => console.log((c ? 'ok  ' : 'FAIL') + ' ' + m);
await p.goto(process.env.URL); await p.waitForTimeout(700);
await p.click('[aria-label=Settings]'); await p.waitForTimeout(400);
await p.getByText('Import from 1Money').click(); await p.waitForTimeout(400);
await p.setInputFiles('input[type=file]', process.env.CSV); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Import', exact: true }).click(); await p.waitForTimeout(400);
await p.getByText('Go to accounts').click(); await p.waitForTimeout(800);
const before = await p.locator('.total-value').innerText();
await p.click('.nav-item:nth-child(2)'); await p.waitForTimeout(500);
const catBefore = await p.locator('.card').first().innerText();
await p.locator('.cat-tile').filter({ hasText: 'Σπίτι' }).first().click(); await p.waitForTimeout(600);
for (const k of ['3', '0', '0']) await p.click(`.key[aria-label="${k}"]`);
// pick a date 5 days ahead via the hidden date input
const d = new Date(); d.setDate(d.getDate() + 5);
const iso = d.toISOString().slice(0, 10);
await p.locator('.dateline input[type=date]').evaluate((el, v) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, v); el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); }, iso);
await p.waitForTimeout(300);
await p.locator('.dateline').screenshot({ path: process.env.OUT + '/p0.png' });
await p.click('.key[aria-label=Save]'); await p.waitForTimeout(1200);
const after = await p.locator('.total-value').innerText();
ok(before === after, `balance unchanged by a planned expense (${before} → ${after})`);
const hdr = await p.locator('.total-btn').innerText();
ok(/Planned −300/.test(hdr), 'header shows planned line: ' + hdr.replace(/\n/g, ' | '));
const catAfter = await p.locator('.card').first().innerText();
ok(catBefore === catAfter, 'month expense total unchanged');
await p.click('.nav-item:nth-child(3)'); await p.waitForTimeout(900);
ok((await p.locator('.screen').innerText()).includes('Planned'), 'planned row listed in Transactions');
await p.screenshot({ path: process.env.OUT + '/p1.png' });
console.log('errors:', errors.length ? errors : 'none');
await b.close();
